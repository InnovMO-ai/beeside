#!/usr/bin/env node
/**
 * FA Public v1.0 copy inventory. Every customer-facing string that has no approved canonical source is wrapped in NC('<id>', es, en)
 * (NEEDS_CANONICAL_COPY). This script lists them. It never rewrites copy.
 *   node scripts/fa4-copy-inventory.js          -> writes docs/fa4/COPY_INVENTORY.md
 *   node scripts/fa4-copy-inventory.js --check  -> exits 1 when the file is out of date (CI)
 */
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const SOURCES = ["shared/fa-public-engine/src", "frontend/src/fa4", "backend/src/fa4"];
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? (e.name === "__tests__" ? [] : walk(path.join(d, e.name))) : [path.join(d, e.name)]));

const entries = [];
for (const dir of SOURCES) {
  for (const file of walk(path.join(root, dir)).filter((f) => /\.(ts|tsx)$/.test(f) && !/\.test\./.test(f))) {
    const text = fs.readFileSync(file, "utf8");
    const re = /\bNC\(\s*(?:'([^']+)'|"([^"]+)")\s*,\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)"|`((?:[^`\\]|\\.)*)`)\s*,\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)"|`((?:[^`\\]|\\.)*)`)/g;
    let m;
    while ((m = re.exec(text))) {
      const id = m[1] || m[2];
      const es = (m[3] ?? m[4] ?? m[5] ?? "").replace(/\\'/g, "'");
      const en = (m[6] ?? m[7] ?? m[8] ?? "").replace(/\\'/g, "'");
      if (id === "_id") continue; // the helper's own signature
      entries.push({ id, es, en, file: path.relative(root, file) });
    }
  }
}
entries.sort((a, b) => a.id.localeCompare(b.id) || a.file.localeCompare(b.file));
const esc = (s) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

const out = [
  "# FA Public v1.0 — copy inventory (NEEDS_CANONICAL_COPY)",
  "",
  "Generated by `node scripts/fa4-copy-inventory.js`; **do not edit by hand**. Every id below is a string that exists in the Build only to keep the",
  "product usable: it has **no literal source** in the frozen Design, DESIGN_HANDOFF, the Front Catalog or the canonical product files. They are NOT approved.",
  "Resolve by finding approved copy (then replace `NC(...)` by `L(...)`) — never by inventing a new variant. English is verified only against the Journey B EN render.",
  "",
  `Total: ${entries.length} entries.`,
  "",
  "| Id | ES (as built) | EN (as built) | Where |",
  "|---|---|---|---|",
  ...entries.map((e) => `| \`${e.id}\` | ${esc(e.es)} | ${esc(e.en)} | \`${e.file}\` |`),
  "",
].join("\n");

const target = path.join(root, "docs/fa4/COPY_INVENTORY.md");
if (process.argv.includes("--check")) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (current !== out) { console.error("docs/fa4/COPY_INVENTORY.md is out of date: run `node scripts/fa4-copy-inventory.js`"); process.exit(1); }
  console.log(`copy inventory up to date (${entries.length} entries)`);
} else {
  fs.writeFileSync(target, out);
  console.log(`wrote docs/fa4/COPY_INVENTORY.md (${entries.length} entries)`);
}
