#!/usr/bin/env node
/**
 * DSC-07 step 1 — inventory of the YEV «topics that don't apply» rules, for Product. READ-ONLY: it only runs the built engine on witness cases.
 *   node scripts/export-not-applicable-rules.mjs [out.md]      (run `npm run build` first)
 * For each rule: the topics it lists, the declared question + option(s) that trigger it (and that must be absent), the CURRENT engine text (for reference, NOT approved to
 * show) and a blank «approved reason» column for Product. Every row is VERIFIED against the engine: the witness case fires the rule and flipping the trigger removes it.
 */
import fs from 'node:fs';
import { buildYourExpansionView, planFor, emptyAnswers, syncComponents } from '../dist/esm/index.js';
import { SEED_CATALOG } from '../dist/esm/seed.js';

const base = (over = {}) => {
  const a = emptyAnswers('es'); a.destinations = { list: [{ iso: 'MX' }], open: false, sameInAll: null };
  const c = { id: 'c1', destinations: ['MX'], activities: ['sell'], withWhat: ['goods'], presence: 'own_physical', permanence: 'permanent', existing: 'nothing', sellsTo: 'companies', ownBrand: 'no', location: 'defined', carries: ['nothing'], ...over };
  a.components = [c]; return syncComponents(a);
};
const groups = (a) => planFor(a, 'MX').notApplicable;
const frontName = (k) => { const f = SEED_CATALOG.fronts.find((x) => x.key === k); return `${f.nameEs} / ${f.nameEn}`; };
const reasonOf = (a, g) => { const m = buildYourExpansionView(a, SEED_CATALOG, new Date('2026-10-21T12:00:00Z')); const d = m.destinations.find((x) => x.destination === 'MX'); const i = groups(a).indexOf(g); return d?.notApplicable[i]?.reason; };

const RULES = [
  { id: 'NA-sell', group: 'sell', fronts: ['FR_GTM', 'FR_BRAND'],
    question: '«¿Qué planeas hacer en [país]?»', trigger: 'La opción «Vender» NO está marcada, y la presencia NO es «Con un socio o distribuidor». (No se declara «solo invertir».)',
    hit: base({ activities: ['operate'], withWhat: [], presence: 'remote', sellsTo: null, ownBrand: null }), miss: base({ activities: ['sell'], presence: 'remote' }) },
  { id: 'NA-place', group: 'place', fronts: ['FR_SITE'],
    question: '«¿Cómo piensas estar presente en [país]?»', trigger: 'Presencia = «Desde mi país, sin estar allí», «Con un socio o distribuidor» o «Con mi equipo trabajando allí, sin oficina propia». NO aplica con «oficina, planta o local propio», «Comprando una empresa» ni «Aún por definir». (El texto actual cambia entre «sin oficina propia» y las otras dos opciones.)',
    hit: base({ presence: 'remote', carries: ['nothing'] }), miss: base({ presence: 'own_physical' }) },
  { id: 'NA-goods', group: 'goods', fronts: ['FR_TRADE', 'FR_LOGISTICS'],
    question: '«¿Qué vas a vender, producir o comprar en [país]?» y «¿Vas a trasladar a [país] personas de tu empresa o maquinaria desde otro país?»', trigger: '«Bienes físicos» NO está marcado y «Maquinaria, herramientas o equipos de trabajo» NO se traslada.',
    hit: base({ withWhat: ['services'], presence: 'remote' }), miss: base({ withWhat: ['goods'], presence: 'remote' }) },
  { id: 'NA-housing_exit', group: 'housing_exit', fronts: ['FR_STAFF_HOUSING', 'FR_EXIT'],
    question: '«¿Tu proyecto en [país] será permanente o temporal?»', trigger: 'Respuesta = «Permanente».',
    hit: base({ permanence: 'permanent', presence: 'remote' }), miss: base({ permanence: 'temporary', presence: 'remote' }) },
];

const rows = RULES.map((r) => {
  const fires = groups(r.hit).includes(r.group); const flips = !groups(r.miss).includes(r.group);
  return { ...r, verified: fires && flips, current: reasonOf(r.hit, r.group) };
});
if (rows.some((r) => !r.verified)) { console.error('INVENTORY NOT VERIFIED', rows.filter((r) => !r.verified).map((r) => r.id)); process.exit(1); }

const md = `# DSC-07 — inventory of «topics that don't apply» rules (for Product approval)

Generated by \`shared/fa-public-engine/scripts/export-not-applicable-rules.mjs\` from the built engine (read-only). Every row is verified: the witness answers fire the rule and flipping the trigger removes it.

Display conditions common to all rules: shown only when the destination is the only one or its presence is already defined (not «Aún por definir»); never when the project is «solo invertir»; **at most 3 groups**, in this priority: sell → place → goods → housing_exit (a 4th is dropped).

**Today the YEV shows these topics WITHOUT a reason** (PO, 2026-10-21: no safe explanation → no reason). Step 2 is Product's: write one natural ES/EN reason per rule faithful to the declared option, or mark «sin razón». Step 3 (Code) implements the approved table as is, with one test per rule.

| Rule | Topics listed (ES / EN) | Declared question | Declared answer that triggers it | Current engine text (ES / EN) — NOT approved | Approved reason ES / EN (Product) |
|---|---|---|---|---|---|
${rows.map((r) => `| \`${r.id}\` | ${r.fronts.map(frontName).join('<br>')} | ${r.question} | ${r.trigger} | ${r.current ? `${r.current.es} / ${r.current.en}` : '—'} | _pendiente_ |`).join('\n')}

Other places that currently show a reason for the same rules (decision for Product: keep, apply the approved table, or drop): the topics screen of the questionnaire («No aplican, por lo que nos contaste»).
`;
fs.writeFileSync(process.argv[2] ?? 'docs-DSC07.md', md);
console.log(md);
